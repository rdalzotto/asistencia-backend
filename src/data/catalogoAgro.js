// Aplana los ítems de un módulo: resuelve subtítulos, orden y valores por defecto.
function itemsDeModulo(modulo) {
  const out = [];
  let grupo = null;
  for (const it of modulo.items) {
    if (typeof it === 'string') { grupo = it.slice(1); continue; }
    const [codigo, texto, ref_normativa, tipo, criticidad, nivel, medida_sugerida] = it;
    out.push({
      codigo, grupo, texto, ref_normativa, tipo, criticidad, nivel,
      medida_sugerida: medida_sugerida || null,
      foto_obligatoria_nc: criticidad === 1,
      orden: out.length,
    });
  }
  return out;
}

